-- อะไหล่ที่ซื้อจากร้านอะไหล่มาใช้เลย ไม่ได้เก็บสต็อก
-- เดิมช่างพิมพ์ชื่อลงบรรทัด "บริการอื่นๆ" ซึ่งทำให้ค่าอะไหล่ถูกนับเป็นค่าบริการ
-- แยกเป็นรายการเปล่าของตัวเอง เร็วเท่าเดิมแต่แยกยอดอะไหล่กับค่าแรงได้ภายหลัง
INSERT IGNORE INTO `Service` (`name`, `price`, `categoryId`, `createdAt`, `updatedAt`)
SELECT 'อะไหล่อื่นๆ', 0, c.id, NOW(3), NOW(3)
FROM `Category` c
WHERE c.name = 'บริการ';
