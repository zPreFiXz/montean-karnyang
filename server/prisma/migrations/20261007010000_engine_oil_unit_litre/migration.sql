-- น้ำมันเครื่องขวดลิตรขายเป็นลิตรได้แล้ว (เปิดขวดตวงได้) หน่วยจึงเป็นลิตร 1 ขวด = 1 ลิตร สต็อกเท่าเดิม
-- ชุดน้ำมันเครื่อง+ไส้กรองยังขายเป็นชุด ไม่เปลี่ยน
UPDATE `Part` p
JOIN `Category` c ON c.`id` = p.`categoryId`
SET p.`unit` = 'ลิตร'
WHERE c.`name` = 'น้ำมัน'
  AND p.`name` LIKE '(1L)%น้ำมันเครื่อง%'
  AND p.`name` NOT LIKE '%ชุด%'
  AND p.`unit` = 'ขวด';
