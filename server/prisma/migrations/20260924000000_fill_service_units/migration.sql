-- ใส่หน่วยให้บริการที่มีอยู่เดิม อ้างด้วยชื่อ เพราะรหัสของแต่ละเครื่องไม่ตรงกัน
-- แตะเฉพาะที่ยังไม่มีหน่วย ถ้าร้านตั้งเองไว้แล้วจะไม่เขียนทับ
-- บริการที่คิดครั้งเดียวต่อคัน (ค่าแรง ตั้งศูนย์ ค่าบริการต่างๆ) ไม่ใส่หน่วย

-- คิดตามล้อที่ทำ
UPDATE `Service` SET `unit` = 'ล้อ'
WHERE `unit` IS NULL AND `name` IN (
  'ถ่วงล้อ',
  'เจียรดิสก์เบรก',
  'เจียรดรัมเบรก',
  'อัดกาวขอบแมกซ์'
);

-- คิดตามเส้นยางที่ถอดใส่
UPDATE `Service` SET `unit` = 'เส้น'
WHERE `unit` IS NULL AND `name` IN (
  'ถอด-ใส่ยาง',
  'ถอด-ใส่ยาง (มอเตอร์ไซค์)'
);

-- คิดตามรอยรั่วที่ปะ
UPDATE `Service` SET `unit` = 'รู'
WHERE `unit` IS NULL AND `name` IN (
  'ปะยาง',
  'ปะยาง (แผ่นใหญ่)',
  'ปะยางรถมอเตอร์ไซค์ (ไหมเสียบ)',
  'ปะยางรถมอเตอร์ไซค์ (สตรีมเย็น)',
  'ปะยางนอกรถหกล้อ',
  'ปะยางในรถหกล้อ (สตรีมร้อน)',
  'ปะยางในรถไถ ล้อหน้า (สตรีมเย็น)'
);

-- จุ๊บลมนับเป็นตัว ล้อละหนึ่งตัว
UPDATE `Service` SET `unit` = 'ตัว'
WHERE `unit` IS NULL AND `name` IN (
  'จุ๊บลม',
  'เปลี่ยนจุ๊บลม'
);

-- เช็กทั้งคัน
UPDATE `Service` SET `unit` = 'คัน'
WHERE `unit` IS NULL AND `name` IN (
  'เช็กเดินทางไกล'
);
