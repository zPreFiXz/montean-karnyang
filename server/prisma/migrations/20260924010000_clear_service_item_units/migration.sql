-- บริการปกติดึงหน่วยจากตารางบริการตอนแสดงผล เหมือนอะไหล่ที่ดึงจากสต็อก
-- บรรทัดที่เคยเก็บหน่วยลงบิลไว้ระหว่างนั้นต้องล้างออก ไม่งั้นจะค้างหน่วยเก่าเมื่อแก้หน่วยของบริการ
-- เก็บไว้เฉพาะรายการเปล่าที่ช่างพิมพ์หน่วยเอง
UPDATE `RepairItem` ri
JOIN `Service` s ON s.id = ri.serviceId
SET ri.itemUnit = NULL
WHERE ri.itemUnit IS NOT NULL
  AND s.name NOT IN ('อะไหล่อื่นๆ', 'บริการอื่นๆ');
