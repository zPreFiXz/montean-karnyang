-- วิธีชำระเงินต้องว่างได้ เพราะบิลที่ยังไม่เก็บเงินยังไม่รู้ว่าลูกค้าจะจ่ายทางไหน
-- ของเดิมตั้งค่าเริ่มต้นเป็น CASH ทุกใบ หน้าบิลจึงขึ้นว่าเงินสดไว้ก่อนตั้งแต่ยังไม่ได้เลือก
-- แล้วกดปิดบิลผ่านไปได้โดยไม่มีใครเลือกจริง
ALTER TABLE `Repair` MODIFY `paymentMethod` ENUM('CASH', 'QR_CODE', 'CREDIT_CARD') NULL;

-- บิลที่ยังไม่ได้เก็บเงินไม่ควรมีวิธีชำระเงินค้างอยู่ ส่วนบิลที่จ่ายแล้วเก็บค่าเดิมไว้ตามจริง
UPDATE `Repair` SET `paymentMethod` = NULL WHERE `paidAt` IS NULL;
