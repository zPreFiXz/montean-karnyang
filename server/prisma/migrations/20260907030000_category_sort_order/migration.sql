-- แถบหมวดหมู่เดิมเรียงตามรหัส ซึ่งคือลำดับที่เพิ่มเข้าระบบ
-- หมวดที่เพิ่มทีหลังจึงไปต่อท้ายเสมอ แม้ของข้างในจะอยู่กลุ่มเดียวกับหมวดที่อยู่ต้นแถว
ALTER TABLE `Category` ADD COLUMN `sortOrder` INT NOT NULL DEFAULT 999;

-- เว้นช่วงทีละ 10 เผื่อแทรกหมวดใหม่ระหว่างกลางภายหลัง
UPDATE `Category` SET `sortOrder` = `id` * 10;

-- ระบบส่งกำลังอยู่ต่อจากคลัช-เกียร์ (รหัส 8) เพราะเป็นระบบเดียวกัน
UPDATE `Category` SET `sortOrder` = 85 WHERE `name` = 'ระบบส่งกำลัง';
