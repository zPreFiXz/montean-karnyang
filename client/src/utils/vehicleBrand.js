export const OTHER_BRAND = "อื่นๆ";

// ยี่ห้อเรียงตามลำดับที่ตั้งใจไว้ในฐานข้อมูล (id) ไม่ใช่ตามตัวอักษร — ห้ามแตะลำดับนั้น
// ตรึงไว้อย่างเดียวคือ "อื่นๆ" ที่เป็นตัวเลือกสำรอง ไม่ใช่ยี่ห้อจริง จึงต้องอยู่ท้ายเสมอ
// (ไม่งั้นพอเพิ่มยี่ห้อใหม่ id จะต่อท้าย แล้ว "อื่นๆ" ไปแทรกกลางลิสต์)
export const withOtherBrandLast = (brands = []) => [
  ...brands.filter((b) => b !== OTHER_BRAND),
  ...brands.filter((b) => b === OTHER_BRAND),
];
